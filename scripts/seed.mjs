async function run() {
  console.log('→ Экспонаты...')
  for (const row of exhibits) {
    const { error } = await supabase.from('exhibits').insert(row)
    if (error) throw error
  }

  console.log('→ Разделы экспозиции...')
  for (const row of collections) {
    const { error } = await supabase.from('collections').insert(row)
    if (error) throw error
  }

  console.log('→ Категории и предметы зала «Быт»...')
  for (const { items, ...category } of bytCategories) {
    const { data: inserted, error } = await supabase.from('byt_categories').insert(category).select().single()
    if (error) throw error

    const itemRows = items.map((item, i) => ({ ...item, category_id: inserted.id, sort_order: i }))
    const { error: itemsError } = await supabase.from('byt_items').insert(itemRows)
    if (itemsError) throw itemsError
  }

  console.log('→ Новости...')
  for (const row of newsPosts) {
    const { error } = await supabase.from('news_posts').insert(row)
    if (error) throw error
  }

  console.log('✔ Готово! Контент перенесён в Supabase.')
}

run().catch((err) => {
  console.error('✖ Ошибка при переносе данных:', err.message || err)
  process.exit(1)
})
